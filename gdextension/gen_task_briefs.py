#!/usr/bin/env python
"""
Generates gen/task_briefs.gen.h: the brief and the full description of every documented
class, as plain text, for the task palette. The brief (wrapped at 80 columns) is the hover
tooltip; the full description fills the palette's description pane.

The GDExtension build registers doc_classes/*.xml with the editor, but an extension has no
way to read EditorHelp back, so the palette carries its own copy of the descriptions.
The header is rewritten only when its content changes, so an unchanged doc set does not
rebuild the palette.
"""

import glob
import os
import re
import textwrap
import xml.etree.ElementTree as ET

_REF_TAG = re.compile(r"\[(?:member|method|signal|constant|enum|param|annotation|constructor|operator|theme_item) ([^\]]+)\]")
_FORMAT_TAG = re.compile(r"\[/?(?:code|b|i|u|s|kbd|codeblock|codeblocks|gdscript|csharp|center|br)\]")
_URL_TAG = re.compile(r"\[url=[^\]]*\]|\[/url\]")
_CLASS_TAG = re.compile(r"\[([A-Z@][A-Za-z0-9_.]*)\]")


def _plain(p_bbcode):
    text = _REF_TAG.sub(r"\1", p_bbcode)
    text = _FORMAT_TAG.sub("", text)
    text = _URL_TAG.sub("", text)
    text = _CLASS_TAG.sub(r"\1", text)
    return " ".join(text.split())


def _c_string(p_text):
    return '"' + p_text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def generate_task_briefs_header(p_doc_dir="doc_classes", p_out_path="gen/task_briefs.gen.h"):
    entries = []
    for path in sorted(glob.glob(os.path.join(p_doc_dir, "*.xml"))):
        root = ET.parse(path).getroot()
        name = root.get("name")
        brief = _plain(root.findtext("brief_description") or "")
        # One paragraph per source line; the pane wraps them itself.
        paragraphs = [_plain(l) for l in (root.findtext("description") or "").strip().splitlines()]
        paragraphs = [p for p in paragraphs if p]
        if not brief and paragraphs:
            brief = paragraphs[0]
        if name and brief:
            # Wrapped here: an editor tooltip does not wrap on its own.
            description = "\n\n".join(paragraphs) if paragraphs else brief
            entries.append((name, textwrap.fill(brief, 80), description))

    out = [
        "// Generated by gdextension/gen_task_briefs.py from doc_classes/*.xml. Do not edit.",
        "#pragma once",
        "",
        "// { class name, brief, full description }",
        "static const char *const LIMBO_TASK_BRIEFS[][3] = {",
    ]
    out += ["\t{ %s, %s, %s }," % (_c_string(n), _c_string(b), _c_string(d)) for n, b, d in entries]
    out += ["};", ""]
    content = "\n".join(out)

    os.makedirs(os.path.dirname(p_out_path), exist_ok=True)
    if os.path.exists(p_out_path):
        with open(p_out_path, "r", encoding="utf-8") as f:
            if f.read() == content:
                return
    with open(p_out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


if __name__ == "__main__":
    generate_task_briefs_header()
